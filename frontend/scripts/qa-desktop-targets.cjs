const assert=require('node:assert/strict');
const {mkdtemp,readFile,readdir}=require('node:fs/promises');
const os=require('node:os'),path=require('node:path');
const {collectionContext,collectionFile,checkContext,parseHotels,readTargets,saveTargets}=require('../desktop/collection-targets.cjs');
(async()=>{
 const root=await mkdtemp(path.join(os.tmpdir(),'staycraft-targets-'));
 const a={userId:'account-a',propertyId:'property-a',location:'苏州市 浏河镇'};
 const b={userId:'account-b',propertyId:'property-b',location:a.location};
 const moved={...a,location:'乌镇西栅'};
 const hotels='https://hotels.ctrip.com/hotels/123456.html 浏河测试住宿';
 const contextKey=collectionContext(a);
 const initial=await readTargets(root,a);assert.equal(initial.hotels,'');assert.equal(initial.savedAt,null);
 await saveTargets(root,a,{hotels,contextKey});
 assert.equal((await readTargets(root,a)).hotels,hotels);
 assert.equal((await readTargets(root,{...a,location:'苏州市浏河镇'})).hotels,hotels);
 assert.equal((await readTargets(root,b)).hotels,'');assert.equal((await readTargets(root,moved)).hotels,'');
 assert.notEqual(collectionFile(root,a),collectionFile(root,moved));assert.notEqual(collectionFile(root,a),collectionFile(root,b));
 await assert.rejects(()=>saveTargets(root,b,{hotels,contextKey}),/collection_context_changed/);
 await assert.rejects(()=>saveTargets(root,moved,{hotels,contextKey}),/collection_context_changed/);
 assert.throws(()=>checkContext({...a,location:''},contextKey),/property_location_required/);
 await saveTargets(root,moved,{hotels:hotels.replace('123456','654321'),contextKey:collectionContext(moved)});
 assert.equal((await readTargets(root,a)).hotels,hotels);
 for(const value of ['https://evil.test/hotels/1.html name','https://hotels.ctrip.com/hotels/1.html    ',hotels+'\n'+hotels,'https://hotels.ctrip.com/hotels/1.html name\u0000'])assert.throws(()=>parseHotels(value),/invalid_hotels/);
 assert.throws(()=>parseHotels(Array.from({length:6},(_,i)=>`https://hotels.ctrip.com/hotels/${i+1}.html name`).join('\n')),/invalid_hotels/);
 await saveTargets(root,a,{hotels:'',contextKey});assert.equal((await readTargets(root,a)).hotels,'');
 const files=await readdir(path.join(root,'targets'));assert.equal(files.length,2);assert(files.every(name=>/^[a-f0-9]{64}\.json$/.test(name)));
 const file=await readFile(path.join(root,'targets',collectionContext(moved)+'.json'),'utf8');assert(!/token|cookie|session|password/i.test(file));
 console.log('PASS desktop targets: persisted selection, account/property/address isolation, address return, stale request blocking, empty selection, URL/name/limit validation and atomic files. Local files only.');
})().catch(error=>{console.error(error);process.exitCode=1});
