const assert=require('node:assert/strict');
const {createSample}=require('./operator-sample-data.cjs');
const {planDemoOrders,assertReviewedPlan}=require('./sync-hosted-demo.cjs');
const anchor='2026-11-11',sample=createSample(anchor,{rich:true});
const initial=planDemoOrders(sample,sample.inventory,[],anchor);
assert.equal(initial.selected.length,125);
assert(initial.selected.some(b=>b.status==='completed'&&b.departure>='2026-11-05'));
assert(initial.selected.some(b=>b.departure>'2026-11-20'));
assert(initial.selected.every(b=>b.channel==='DEMO-RICH'&&b.externalId.startsWith('20261111-')&&b.currency==='CNY'&&Number.isSafeInteger(b.totalCents)));
const s=sample.bookings.find(b=>b.status==='confirmed');
const original={id:'preserved',room_id:s.room_id,room_number:s.room_number,type_id:s.type_id,arrival:s.arrival,departure:s.departure,status:'confirmed'};
const serialized=JSON.stringify(original);
const conflict=planDemoOrders(sample,sample.inventory,[original],anchor);
assert(conflict.skipped.some(b=>b.reason==='existing_room_dates'));
assert.equal(JSON.stringify(original),serialized);
const retry=planDemoOrders(sample,sample.inventory,initial.selected.map(b=>({external_channel:b.channel,external_id:b.externalId,status:'cancelled'})),anchor);
assert.equal(retry.selected.length,0);
assert.equal(retry.skipped.length,125);
assert.throws(()=>planDemoOrders(sample,{...sample.inventory,types:[]},[],anchor),/room_type_mapping/);
assert.throws(()=>planDemoOrders(sample,{...sample.inventory,rooms:[]},[],anchor),/room_mapping/);
const reviewed={ordersHash:'orders',profileHash:'profile',rows:[],batch:{quote_count:42},nextProfile:{location:'reviewed location',notes:'demo'}};
assert.doesNotThrow(()=>assertReviewedPlan(reviewed,structuredClone(reviewed)));
for(const key of ['location','notes'])assert.throws(()=>assertReviewedPlan(reviewed,{...reviewed,nextProfile:{...reviewed.nextProfile,[key]:'changed after preview'}}),/reviewed_plan_changed/);
console.log('PASS 13 demo sync checks: coverage, mapping, conflicts, preservation, stable identity and reviewed profile binding.');
