import {parseCalendar,compareObservations,captureBarrier,buildPriceWatch} from '../src/lib/competitor-observations.ts';
import assert from 'node:assert/strict';
const base={hotelId:'2132616',hotelName:'sample',capturedAt:'2026-10-31T03:00:00Z',dates:['2026-11-04']};
const label='- checkbox "2026年11月4日(星期三), The price is CNY 221, Select the start date you want"';
const read=snapshot=>parseCalendar({...base,snapshot:'sample 1间, 2成人, 0儿童\n'+snapshot})[0];
assert.equal(read(label).amount,221);
assert.equal(read(label+'\n'+label).amount,221);
assert.equal(read(label+'\n'+label.replace('221','230')).status,'conflicting');
assert.equal(read('自行车每天¥15 会议厅¥150').amount,null);
assert.equal(read('登录看低价').status,'login_required');
assert.equal(read('本酒店目前不接受预订').status,'not_accepting');
assert.equal(read(label+'\n登录看低价').status,'observed');
const previous=read(label),next={...previous,capturedAt:'2026-10-31T04:00:00Z',amount:231};
assert.equal(compareObservations(next,previous),10);
assert.equal(compareObservations({...next,stayDate:'2026-11-07'},previous),null);
assert.equal(compareObservations({...next,status:'missing',amount:null},previous),null);
assert.equal(compareObservations(previous,next),null);
assert.throws(()=>parseCalendar({...base,snapshot:label}),/capture_context_missing/);
assert.throws(()=>parseCalendar({...base,hotelId:'../1',snapshot:label}),/invalid_capture/);
console.log('13 calendar parsing, context and comparison checks passed');

assert.equal(captureBarrier('https://passport.ctrip.com/user/login','验证码登录'),'login_required');
assert.equal(captureBarrier('https://hotels.ctrip.com/hotels/1.html','登录看低价'),null);
assert.equal(captureBarrier('https://hotels.ctrip.com/hotels/1.html','请完成安全验证'),'verification_required');
assert.equal(captureBarrier('https://hotels.ctrip.com/hotels/1.html','账号密码登录'),'login_required');
console.log('4 landing-page classification checks passed');
const scope='member:00000000-0000-4000-8000-000000000001';
assert.equal(compareObservations({...next,authScope:scope},previous),null);
assert.equal(compareObservations({...next,authScope:scope},{...previous,authScope:'member:00000000-0000-4000-8000-000000000002'}),null);
assert.equal(compareObservations({...next,authScope:scope},{...previous,authScope:scope}),10);
console.log('3 member-session isolation checks passed');
const member={...next,authScope:scope},now=Date.parse('2026-10-31T04:01:00Z');
const job={status:'succeeded',startedAt:'2026-10-31T03:59:00Z',finishedAt:'2026-10-31T04:00:30Z',dates:['2026-11-04']};
const watch=buildPriceWatch([previous,{...previous,authScope:scope},member],job,scope,now);
assert.equal(watch.rows[0].amount,231);
assert.equal(watch.rows[0].change,10);
assert.equal(watch.rows[0].history.length,2); // Anonymous record never enters the member history.
assert.equal(watch.rows[1].amount,null); // Missing hotel is still represented.
const failed=buildPriceWatch([member],{...job,startedAt:'2026-10-31T04:00:10Z',results:[{hotelId:'2132616',status:'failed',error:'page_timeout'}]},scope,now).rows[0];
assert.equal(failed.amount,null);
assert.equal(failed.status,'page_timeout');
assert.equal(failed.lastGood.amount,231);
const stale=buildPriceWatch([member],job,scope,now+7*3600000).rows[0];
assert.equal(stale.amount,null);
assert.equal(stale.status,'stale');
assert.equal(buildPriceWatch([member],job,'member:00000000-0000-4000-8000-000000000002',now).rows[0].history.length,0);
console.log('10 price-watch freshness, failure and session checks passed');
const nextDay={...member,capturedAt:'2026-11-01T03:00:00Z',amount:241};
const nextDayJob={...job,startedAt:'2026-11-01T02:59:00Z',finishedAt:'2026-11-01T03:00:30Z'};
const continued=buildPriceWatch([member,nextDay],nextDayJob,scope,Date.parse('2026-11-01T03:01:00Z')).rows[0];
assert.equal(continued.change,10);
assert.equal(continued.history.length,2);
assert.equal(buildPriceWatch([member],{...nextDayJob,error:'browser_unavailable'},scope,Date.parse('2026-11-01T03:01:00Z')).rows[0].status,'browser_unavailable');
console.log('3 cross-day continuity and startup-error checks passed');
const unverified=buildPriceWatch([{...member,conditions:{roomType:'test',breakfast:'included',comparable:true}}],job,scope,now).rows[0];
assert.deepEqual(unverified.conditions,{roomType:null,breakfast:null,cancellation:null,taxes:null,comparable:false});
console.log('1 calendar offer-condition isolation check passed');
assert.equal(captureBarrier('https://hotels.ctrip.com/hotels/2132616.html','携程旅行 请完成下面的验证测试。'),'verification_required');
assert.equal(captureBarrier('https://hotels.ctrip.com/hotels/2132616.html','请按顺序点选图标'),'verification_required');
console.log('2 observed Ctrip cloud verification-page classification checks passed');
